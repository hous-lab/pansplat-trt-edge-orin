#!/usr/bin/env python3
"""Generate scripts/release_manifest.yaml from the ground truth in cxx/runner.cu.

The runner's load_engine/load_bin calls are the single source of truth for what
a complete deployment chain consists of. This script parses them and records,
per engine: the buffer-table key, the engine file, the ONNX segment it is built
from, and the release script that produces that ONNX. The manifest is used:

Regenerable artifacts are hashed at build time by the pipeline (export/.ok/
sentinels), not here - the manifest records structure, not volatile checksums.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
RUNNER = REPO / "cxx" / "runner.cu"
MANIFEST = REPO / "scripts" / "release_manifest.yaml"

ENGINE_RE = re.compile(
    r'load_engine\("([^"]+)",\s*std::string\(eng_dir\)\s*\+\s*"/([^"]+\.engine)"\)'
)
BIN_RE = re.compile(r'load_bin\(std::string\(bin_dir\)\s*\+\s*"/([^"]+\.bin)"')

# ONNX stem -> producing script in scripts/ (release-tree names).
PRODUCER_RULES = [
    (re.compile(r"^(mvs_pre|cv_pre[012]|cv_post0)$"), "scripts/export_cv_split.py"),
    (re.compile(r"^p[12]_"), "scripts/export_split_post.py"),
    (re.compile(r"^gh_s[01]_"), "scripts/export_gh_s01.py"),
    (re.compile(r"^gh_s[23]_"), "scripts/export_fine.py"),
]

GOLDEN = "export/golden_512.npz"


def parse_runner() -> tuple[list[tuple[str, str]], list[str]]:
    """Extract (key, engine_file) pairs and input .bin names from runner.cu."""
    text = RUNNER.read_text()
    engines = []
    seen = set()
    for m in ENGINE_RE.finditer(text):
        key, engine = m.group(1), m.group(2)
        if key in seen:
            continue
        seen.add(key)
        engines.append((key, engine))
    bins = list(dict.fromkeys(BIN_RE.findall(text)))
    return engines, bins


def producer_for(onnx_stem: str) -> str:
    for rule, script in PRODUCER_RULES:
        if rule.search(onnx_stem):
            return script
    raise SystemExit(f"no producer rule matches ONNX stem {onnx_stem!r}")


def build_manifest() -> dict:
    engines, bins = parse_runner()
    if len(engines) != 21:
        raise SystemExit(f"expected 21 engines in runner.cu, parsed {len(engines)}")
    entries = []
    for key, engine in engines:
        stem = engine.removesuffix(".engine")
        entries.append(
            {
                "key": key,
                "engine": engine,
                "onnx": f"export/onnx/{stem}.onnx",
                "producer": producer_for(stem),
            }
        )
    return {
        "engines": entries,
        "inputs": [f"export/runner_bins/{b}" for b in bins],
        "golden": GOLDEN,
        "forbidden": [
            "export/runner_bins/**",
            "export/calib/**",
            "logs/**/checkpoints/**",
            "*.ckpt",
        ],
    }


def emit_yaml(m: dict) -> str:
    out = ["# Generated by scripts/gen_release_manifest.py - do not hand-edit.",
           "# Ground truth: cxx/runner.cu load_engine/load_bin calls."]
    for section, items in (("engines", m["engines"]), ("inputs", m["inputs"])):
        out.append(f"{section}:")
        for it in items:
            if isinstance(it, dict):
                out.append(f"  - key: {it['key']}")
                out.append(f"    engine: {it['engine']}")
                out.append(f"    onnx: {it['onnx']}")
                out.append(f"    producer: {it['producer']}")
            else:
                out.append(f"  - {it}")
    out.append(f"golden: {m['golden']}")
    out.append("forbidden:")
    for f in m["forbidden"]:
        out.append(f"  - {f}")
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--check",
        action="store_true",
        help="verify the committed manifest matches runner.cu instead of rewriting it",
    )
    args = ap.parse_args()
    expected = emit_yaml(build_manifest())
    if args.check:
        if not MANIFEST.exists():
            print("missing scripts/release_manifest.yaml", file=sys.stderr)
            return 1
        have = MANIFEST.read_text()
        if have != expected:
            import difflib

            diff = "".join(
                difflib.unified_diff(
                    have.splitlines(True),
                    expected.splitlines(True),
                    fromfile="release_manifest.yaml (committed)",
                    tofile="expected from runner.cu",
                )
            )
            print(diff, file=sys.stderr)
            print(
                "manifest drifted from cxx/runner.cu - regenerate with "
                "scripts/gen_release_manifest.py",
                file=sys.stderr,
            )
            return 1
        print(f"manifest ok: {len(build_manifest()['engines'])} engines, "
              f"{len(build_manifest()['inputs'])} inputs")
        return 0
    MANIFEST.write_text(expected)
    print(f"wrote {MANIFEST.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
